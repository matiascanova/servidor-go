-- email y password_hash admiten NULL a propósito: así el usuario demo del seed.sql
-- (que solo trae id, nombre y apellido) sigue cargando sin errores. Ese usuario
-- simplemente no puede iniciar sesión. La app exige ambos campos al registrarse.
CREATE TABLE usuario (
	idUsuario int GENERATED BY DEFAULT AS IDENTITY,
	nombre varchar(50) NOT NULL,
	apellido varchar(50) NOT NULL,
	email varchar(120) NULL,
	password_hash text NULL,
	CONSTRAINT usuario_pk PRIMARY KEY (idUsuario),
	CONSTRAINT usuario_email_uk UNIQUE (email)
);

CREATE TABLE voto (
    idUsuario int NOT NULL,
    idMateria int NOT NULL,
    puntuacion_dif int NULL,
    puntuacion_rel int NULL,
    puntuacion_gusto int NULL,
    descripcion varchar(140) NULL,
    fecha_voto date NOT NULL DEFAULT CURRENT_TIMESTAMP ,
    CONSTRAINT voto_pk PRIMARY KEY (idUsuario,idMateria),
    CONSTRAINT chk_al_menos_un_voto CHECK (
            puntuacion_dif IS NOT NULL OR 
            puntuacion_rel IS NOT NULL OR 
            puntuacion_gusto IS NOT NULL
        ),
    CONSTRAINT chk_rango_votos CHECK (
        (puntuacion_dif BETWEEN 1 AND 5 OR puntuacion_dif IS NULL) AND
        (puntuacion_rel BETWEEN 1 AND 5 OR puntuacion_rel IS NULL) AND
        (puntuacion_gusto BETWEEN 1 AND 5 OR puntuacion_gusto IS NULL)
    )
);

CREATE TABLE materia (
	idMateria int NOT NULL, 
	nombre varchar(50) NOT NULL,
	cuatrimestre int NOT NULL,
	descripcion varchar(50) NULL,
	CONSTRAINT materia_pk PRIMARY KEY (idMateria)
);

-- Sesiones de login. Se guarda el hash SHA-256 del token (nunca el token en claro):
-- si alguien lee la tabla, no puede usar las cookies de los usuarios.
CREATE TABLE sesion (
	token_hash varchar(64) NOT NULL,
	idUsuario int NOT NULL,
	expira timestamptz NOT NULL,
	CONSTRAINT sesion_pk PRIMARY KEY (token_hash)
);

CREATE INDEX idx_sesion_usuario ON sesion (idUsuario);

ALTER TABLE voto
ADD CONSTRAINT fk_usuario FOREIGN KEY (idUsuario) REFERENCES usuario (idUsuario)
ON UPDATE CASCADE
ON DELETE CASCADE;

ALTER TABLE voto
ADD CONSTRAINT fk_materia FOREIGN KEY (idMateria) REFERENCES materia(idMateria)
ON UPDATE CASCADE
ON DELETE CASCADE;

ALTER TABLE sesion
ADD CONSTRAINT fk_sesion_usuario FOREIGN KEY (idUsuario) REFERENCES usuario (idUsuario)
ON UPDATE CASCADE
ON DELETE CASCADE;
